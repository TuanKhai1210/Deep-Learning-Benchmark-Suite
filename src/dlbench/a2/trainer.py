"""Epoch-boundary resume with immutable settings and atomic authoritative state.

last.pt contains history and RNG so an interrupted history.json write is repaired
on resume. Mid-epoch resume and cross-device bitwise identity are not promised.
Only load checkpoints generated by this project that you trust (torch pickle).
"""
from __future__ import annotations

from pathlib import Path
import hashlib
import importlib.metadata
import json
import os
import subprocess
import uuid

import torch
from dlbench.common.reproducibility import (
    seed_everything, capture_rng_state, restore_rng_state, collect_environment,
)
from .config import validate_config
from .data import content_hash, make_loader
from .engine import run_epoch
from .losses import SegmentationLoss
from .models import build_model, count_parameters


def save_json(path, value):
    path = Path(path)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n",
                         encoding="utf-8")
    os.replace(temporary, path)


def atomic_save(path, value):
    path = Path(path)
    temporary = path.with_name(path.name + ".tmp")
    torch.save(value, temporary)
    os.replace(temporary, path)


def state_hash(model):
    digest = hashlib.sha256()
    for name, tensor in sorted(model.state_dict().items()):
        digest.update(name.encode())
        digest.update(str(tensor.dtype).encode())
        digest.update(str(tuple(tensor.shape)).encode())
        digest.update(tensor.detach().cpu().contiguous().numpy().tobytes())
    return digest.hexdigest()


def source_identity():
    root = Path(__file__).resolve().parents[3]
    def git(*args):
        return subprocess.check_output(["git", "-C", str(root), *args], stderr=subprocess.DEVNULL).decode("utf-8")
    files = sorted((root / "src/dlbench/a2").rglob("*.py"))
    files += sorted((root / "configs/a2").rglob("*.py"))
    files += sorted((root / "src/dlbench/common").glob("*.py"))
    hashes = {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
    try:
        revision, status, diff = git("rev-parse", "HEAD").strip(), git("status", "--porcelain"), git("diff", "HEAD", "--", "src", "configs", "setup.py")
    except (OSError, subprocess.CalledProcessError):
        revision, status, diff = None, "git unavailable", ""
    return {"revision": revision, "status": status, "tracked_diff": diff,
            "source_sha256": hashes, "source_digest": content_hash(hashes)}


def is_better(candidate, best):
    score = candidate["foreground_miou"]
    if score is None:
        raise ValueError("Validation has no defined foreground classes")
    return best is None or score > best["foreground_miou"] or (
        score == best["foreground_miou"] and candidate["loss"] < best["loss"])


def fit(config, train_data, validation_data, output, *, device="cpu", workers=0,
        development=False, epochs=None, resume=False):
    validate_config(config, main=not development)
    budget = config["budget"]
    max_epochs = epochs if epochs is not None else budget["epochs"]
    if type(max_epochs) is not int or not 1 <= max_epochs <= budget["epochs"]:
        raise ValueError("epochs must be within configured budget")
    if not development and max_epochs != budget["epochs"]:
        raise ValueError("Main run must use configured budget")
    if train_data.split != "train" or validation_data.split != "validation":
        raise ValueError("fit accepts train and validation only")
    if any(d.manifest_digest != config["data"]["manifest_sha256"] for d in (train_data, validation_data)):
        raise ValueError("Dataset manifest differs from config")
    for dataset in (train_data, validation_data):
        if dataset.preprocessing != config["preprocessing"] or dataset.seed != config["run"]["seed"]:
            raise ValueError("Dataset preprocessing/seed differs from config")
        if dataset.color_jitter != config["run"]["color_jitter"]:
            raise ValueError("Dataset augmentation differs from config")
    device = torch.device(device)
    seed_everything(config["run"]["seed"])
    model = build_model(config["model"]).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=config["training"]["lr"],
                                 weight_decay=config["training"]["weight_decay"])
    criterion = SegmentationLoss(**config["loss"])
    source = source_identity()
    environment = collect_environment()
    dependencies = {}
    for package in ("Pillow", "transformers", "huggingface-hub"):
        try:
            dependencies[package] = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            dependencies[package] = None
    identity = {"config": config, "device": str(device), "workers": workers,
                "development": development, "source_digest": source["source_digest"],
                "environment": environment, "dependencies": dependencies,
                "cpu_threads": torch.get_num_threads(),
                "train_membership": content_hash(train_data.rows),
                "validation_membership": content_hash(validation_data.rows)}
    fingerprint = content_hash(identity)
    output = Path(output)
    history, best, bad_epochs, start = [], None, 0, 0
    if resume:
        metadata = json.loads((output / "metadata.json").read_text(encoding="utf-8"))
        if metadata["identity_sha256"] != fingerprint:
            raise ValueError("Resume config/source/device identity mismatch")
        saved = torch.load(output / "last.pt", map_location="cpu", weights_only=False)
        if saved["identity_sha256"] != fingerprint:
            raise ValueError("Checkpoint identity mismatch")
        model.load_state_dict(saved["model"])
        optimizer.load_state_dict(saved["optimizer"])
        restore_rng_state(saved["rng"])
        start, history, best = saved["epoch"], saved["history"], saved["best"]
        bad_epochs = saved["bad_epochs"]
        # Reconstruct best.pt from last.pt when interruption happened between writes.
        if best is not None and best["epoch"] == start:
            atomic_save(output / "best.pt", saved)
    else:
        output.mkdir(parents=True, exist_ok=False)
        save_json(output / "metadata.json", {
            "run_id": str(uuid.uuid4()), "kind": "development" if development else "main",
            "identity": identity, "identity_sha256": fingerprint, "source": source,
            "environment": environment, "dependencies": dependencies,
            "initial_state_sha256": state_hash(model),
            "parameter_counts": count_parameters(model),
        })
        save_json(output / "effective_config.json", config)
        # Untracked implementation is captured too; git diff alone omits new files.
        root = Path(__file__).resolve().parents[3]
        for relative in source["source_sha256"]:
            target = output / "source" / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes((root / relative).read_bytes())
    for epoch in range(start, max_epochs):
        if bad_epochs >= budget["patience"]:
            break
        train_loader = make_loader(train_data, batch_size=budget["batch_size"],
                                   workers=workers, epoch=epoch)
        val_loader = make_loader(validation_data, batch_size=budget["batch_size"], workers=workers)
        train_metrics = run_epoch(model, train_loader, criterion, device, optimizer)
        validation = run_epoch(model, val_loader, criterion, device)
        candidate = {"epoch": epoch + 1, "foreground_miou": validation["foreground_miou"],
                     "loss": validation["loss"]}
        improved = is_better(candidate, best)
        if improved:
            best, bad_epochs = candidate, 0
        else:
            bad_epochs += 1
        history.append({"epoch": epoch + 1, "train": train_metrics, "validation": validation})
        state = {"identity_sha256": fingerprint, "epoch": epoch + 1,
                 "model": model.state_dict(), "optimizer": optimizer.state_dict(),
                 "rng": capture_rng_state(), "history": history, "best": best,
                 "bad_epochs": bad_epochs}
        atomic_save(output / "last.pt", state)
        if improved:
            atomic_save(output / "best.pt", state)
        save_json(output / "history.json", history)
        save_json(output / "metrics.json", {"best": best, "epochs_completed": len(history),
                                            "kind": "development" if development else "main"})
    # Also repair derived files after resuming a completed/early-stopped run.
    save_json(output / "history.json", history)
    save_json(output / "metrics.json", {"best": best, "epochs_completed": len(history),
                                        "kind": "development" if development else "main"})
    return {"output": str(output), "best": best, "epochs_completed": len(history)}


def evaluate_checkpoint(run_dir, dataset, *, device="cpu", workers=0):
    """Read saved effective config; never select epochs using test data."""
    run_dir = Path(run_dir)
    metadata = json.loads((run_dir / "metadata.json").read_text(encoding="utf-8"))
    config = json.loads((run_dir / "effective_config.json").read_text(encoding="utf-8"))
    validate_config(config)
    if config != metadata["identity"]["config"]:
        raise ValueError("Effective config differs from run identity")
    if content_hash(metadata["identity"]) != metadata["identity_sha256"]:
        raise ValueError("Run identity hash mismatch")
    if source_identity()["source_digest"] != metadata["identity"]["source_digest"]:
        raise ValueError("Evaluation source differs from saved run; use the saved source snapshot")
    if dataset.manifest_digest != config["data"]["manifest_sha256"]:
        raise ValueError("Evaluation manifest mismatch")
    if dataset.split == "train":
        raise ValueError("Evaluation accepts held-out partitions only")
    if dataset.split == "test" and metadata["kind"] != "main":
        raise ValueError("Do not evaluate development checkpoints on the official test split")
    if dataset.preprocessing != config["preprocessing"]:
        raise ValueError("Evaluation preprocessing differs from config")
    saved = torch.load(run_dir / "best.pt", map_location="cpu", weights_only=False)
    if saved["identity_sha256"] != metadata["identity_sha256"]:
        raise ValueError("Checkpoint/run identity mismatch")
    model = build_model(config["model"], pretrained=False).to(device)
    model.load_state_dict(saved["model"])
    loader = make_loader(dataset, batch_size=config["budget"]["batch_size"], workers=workers)
    return {"split": dataset.split, "selected_epoch": saved["epoch"],
            "membership_sha256": content_hash(dataset.rows),
            "kind": metadata["kind"],
            "checkpoint_sha256": hashlib.sha256((run_dir / "best.pt").read_bytes()).hexdigest(),
            "run_identity_sha256": metadata["identity_sha256"],
            "metrics": run_epoch(model, loader, SegmentationLoss(**config["loss"]), device)}
